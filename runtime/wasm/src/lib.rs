/// Accumulated seconds per category for `profiled`.
#[cfg(not(target_arch = "wasm32"))]
pub mod profile {
    use std::{sync::Mutex, time::Instant};

    pub const LOAD: usize = 0;
    pub const CONVERT: usize = 1;
    pub const MATMUL: usize = 2;
    pub const DELTA: usize = 3;
    pub const EMBED: usize = 4;
    pub const LINEAR_ATTENTION: usize = 5;
    pub const FULL_ATTENTION: usize = 6;
    pub const MLP: usize = 7;
    pub const NAMES: [&str; 8] = [
        "weight_load",
        "bf16_to_fp32",
        "matmul",
        "delta_recurrence",
        "embedding_load",
        "linear_attention_block",
        "full_attention_block",
        "mlp_block",
    ];
    static TOTALS: Mutex<[f64; 8]> = Mutex::new([0.0; 8]);

    pub fn add(slot: usize, started: Instant) {
        TOTALS.lock().unwrap()[slot] += started.elapsed().as_secs_f64();
    }

    /// Returns and resets the totals.
    pub fn take() -> [f64; 8] {
        std::mem::take(&mut *TOTALS.lock().unwrap())
    }
}

/// Milliseconds from an arbitrary origin; the page supplies the clock on wasm32.
pub fn now_ms() -> f64 {
    #[cfg(target_arch = "wasm32")]
    {
        wasm::now_ms()
    }
    #[cfg(not(target_arch = "wasm32"))]
    {
        use std::{sync::OnceLock, time::Instant};
        static START: OnceLock<Instant> = OnceLock::new();
        START.get_or_init(Instant::now).elapsed().as_secs_f64() * 1000.0
    }
}

