/// Milliseconds from an arbitrary origin; the page supplies the clock on wasm32.
pub fn now_ms() -> f64 {
    #[cfg(target_arch = "wasm32")]
    {
        wasm::now_ms()
    }
    #[cfg(not(target_arch = "wasm32"))]
    {
        use std::{sync::OnceLock, time::Instant};
        static START: OnceLock<Instant> = OnceLock::new();
        START.get_or_init(Instant::now).elapsed().as_secs_f64() * 1000.0
    }
}

/// Runtime facts recorded with every result.
pub fn environment() -> serde_json::Value {
    serde_json::json!({
        "target_arch": std::env::consts::ARCH,
        "simd128_compiled": cfg!(target_feature = "simd128"),
        "candle_num_threads": candle_core::utils::get_num_threads(),
        "candle_with_simd128": candle_core::utils::with_simd128(),
    })
}
