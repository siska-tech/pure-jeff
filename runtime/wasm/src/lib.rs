//! Browser Wasm feasibility probe. W0: frozen Native operators and tokenizer on small
//! fixtures. W1: one full decision from in-memory assets. Not a DecisionProvider and not a
//! public worker protocol.
pub mod decide;
pub mod ops;
pub mod tokenize;
#[cfg(target_arch = "wasm32")]
mod wasm;

/// Frozen Native backbone, included byte-for-byte (hash-checked by build.rs).
#[allow(dead_code)]
pub mod frozen {
    // Probe-only entry points to the private frozen operators. The frozen file is included
    // last because it ends with its own test module.
    pub fn normalized_op(x: &Tensor, eps: f64) -> Result<Tensor> {
        normalized(x, eps)
    }
    pub fn l2_op(x: &Tensor) -> Result<Tensor> {
        l2(x)
    }
    pub fn rotary_op(x: &Tensor) -> Result<Tensor> {
        rotary(x)
    }
    pub fn delta_recurrence_op(
        q: &Tensor,
        k: &Tensor,
        v: &Tensor,
        beta: &Tensor,
        g: &Tensor,
    ) -> Result<Tensor> {
        delta_recurrence(q, k, v, beta, g)
    }

    include!(concat!(env!("OUT_DIR"), "/backbone.rs"));
}

