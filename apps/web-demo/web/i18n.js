// A message: { key, params } (translated) or { text } (shown as is, e.g. an engine error).
function t(lang, key, params = {}) {
  const template = (MESSAGES[lang] && MESSAGES[lang][key]) ?? MESSAGES[FALLBACK_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => {
    const value = params[name];
    return value === undefined ? match : render(lang, value);
  });
}

function render(lang, value) {
  if (value && typeof value === "object") return value.key ? t(lang, value.key, value.params) : String(value.text ?? "");
  return String(value);
}

// The first of: ?lang=, the saved choice, the browser's languages; otherwise English.
function pickLanguage(search, saved, preferred) {
  const query = new URLSearchParams(search).get("lang");
  for (const candidate of [query, saved, ...preferred]) {
    const code = (candidate || "").toLowerCase().split("-")[0];
    if (code in LANGUAGES) return code;
  }
  return FALLBACK_LANGUAGE;
}

if (typeof module !== "undefined") module.exports = { LANGUAGES, MESSAGES, t, render, pickLanguage };
